"""Rebuild the GO base catalog from PvPoke and PokéAPI. Run by hand.

    uv run python -m scripts.refresh_base_catalog

Downloads only those two projects. It refuses any other host, including
PokeMiners, Bulbapedia, LeekDuck, and pokemongolive.com.
"""

import csv
import json
import urllib.request
from pathlib import Path

from data.catalog_merge import merge_catalog

_HERE = Path(__file__).resolve().parents[1]
_OUT = _HERE / "data" / "go_base.json"
_POKEMON = _HERE / "data" / "pokemon.json"

_PVPOKE = (
    "https://raw.githubusercontent.com/pvpoke/pvpoke/master/"
    "src/data/gamemaster/pokemon.json"
)
_SPECIES = (
    "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/"
    "data/v2/csv/pokemon_species.csv"
)
_DEX = (
    "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/"
    "data/v2/csv/pokemon_dex_numbers.csv"
)
_ALLOWED = {_PVPOKE, _SPECIES, _DEX}
_BLOCKED = ("pokeminers", "bulbapedia", "leekduck", "scrapedduck", "pokemongolive")


def _fetch(url: str) -> str:
    if url not in _ALLOWED or any(part in url.lower() for part in _BLOCKED):
        raise ValueError(f"Refusing to download {url}.")
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read().decode()


def _national_dex(species_csv: str, dex_csv: str) -> dict[str, int]:
    species_rows = list(csv.DictReader(species_csv.splitlines()))
    dex_rows = list(csv.DictReader(dex_csv.splitlines()))
    ident = {row["id"]: row["identifier"] for row in species_rows}
    national: dict[str, int] = {}
    for row in dex_rows:
        if row["pokedex_id"] != "1":
            continue
        slug = ident.get(row["species_id"])
        if slug:
            national[slug] = int(row["pokedex_number"])
    return national


def _names_and_types() -> dict[str, dict[str, object]]:
    payload = json.loads(_POKEMON.read_text())
    return {
        slug: {"name": row["name"], "types": row["types"]}
        for slug, row in payload["pokemon"].items()
    }


def main() -> None:
    pvpoke = json.loads(_fetch(_PVPOKE))
    national = _national_dex(_fetch(_SPECIES), _fetch(_DEX))
    species = merge_catalog(pvpoke, national, _names_and_types())
    document = {
        "note": (
            "Generated by scripts/refresh_base_catalog.py from the PvPoke "
            "gamemaster (MIT) and PokéAPI species data (BSD-3-Clause). "
            "Do not edit by hand. Shiny, Dynamax, Gigantamax, and costumes "
            "are not in this file."
        ),
        "sources": {
            "pvpoke": _PVPOKE,
            "pokeapi_species": _SPECIES,
            "pokeapi_dex": _DEX,
        },
        "species": species,
    }
    _OUT.write_text(json.dumps(document, indent=2) + "\n")
    print(f"Wrote {len(species)} species to {_OUT.name}")


if __name__ == "__main__":
    main()
